function jsonResponse(description, schema, example) {
  return {
    description,
    content: {
      "application/json": {
        schema,
        ...(example ? { example } : {}),
      },
    },
  };
}

// Generate CRUD and existence endpoints for every resource.
for (const resource of resources) {
  const itemSchema = {
    $ref: `#/components/schemas/${resource.schema}`,
  };

  const inputSchema = {
    $ref: `#/components/schemas/${resource.inputSchema}`,
  };

  const basePath = resource.path;
  const itemPath = `${basePath}/{id}`;
  const existsPath = `${basePath}/exists-by-id/{id}`;

  // Collection endpoints.
  swaggerSpec.paths[basePath] = {
    get: {
      tags: [resource.tag],
      summary: resource.listSummary,
      operationId: `list${resource.operationPlural}`,
      responses: {
        200: jsonResponse("List of resources", {
          type: "array",
          items: itemSchema,
        }),
        500: {
          $ref: "#/components/responses/InternalServerError",
        },
      },
    },

    post: {
      tags: [resource.tag],
      summary: resource.createSummary,
      operationId: `create${resource.operationSingular}`,
      requestBody: {
        required: true,
        content: {
          "application/json": {
            schema: inputSchema,
            example: resource.example,
          },
        },
      },
      responses: {
        201: jsonResponse("Resource created", itemSchema),
        400: {
          $ref: "#/components/responses/BadRequest",
        },
        409: {
          $ref: "#/components/responses/Conflict",
        },
        500: {
          $ref: "#/components/responses/InternalServerError",
        },
      },
    },
  };

  // Individual resource endpoints.
  swaggerSpec.paths[itemPath] = {
    parameters: [
      {
        $ref: "#/components/parameters/Id",
      },
    ],

    get: {
      tags: [resource.tag],
      summary: `Get ${resource.singular} by ID`,
      operationId: `get${resource.operationSingular}ById`,
      responses: {
        200: jsonResponse("Resource found", itemSchema),
        400: {
          $ref: "#/components/responses/BadRequest",
        },
        404: {
          $ref: "#/components/responses/NotFound",
        },
        500: {
          $ref: "#/components/responses/InternalServerError",
        },
      },
    },

    put: {
      tags: [resource.tag],
      summary: resource.updateSummary,
      operationId: `update${resource.operationSingular}`,
      requestBody: {
        required: true,
        content: {
          "application/json": {
            schema: {
              type: "object",
              description:
                "Fields to update. Mongoose schema validation is applied.",
              additionalProperties: true,
            },
            example: resource.example,
          },
        },
      },
      responses: {
        200: jsonResponse("Resource updated", itemSchema),
        400: {
          $ref: "#/components/responses/BadRequest",
        },
        404: {
          $ref: "#/components/responses/NotFound",
        },
        409: {
          $ref: "#/components/responses/Conflict",
        },
        500: {
          $ref: "#/components/responses/InternalServerError",
        },
      },
    },

    delete: {
      tags: [resource.tag],
      summary: `Delete ${resource.singular}`,
      operationId: `delete${resource.operationSingular}`,
      responses: {
        200: jsonResponse("Resource deleted", {
          type: "object",
          properties: {
            message: {
              type: "string",
              example: "Resource deleted successfully",
            },
          },
          required: ["message"],
        }),
        400: {
          $ref: "#/components/responses/BadRequest",
        },
        404: {
          $ref: "#/components/responses/NotFound",
        },
        500: {
          $ref: "#/components/responses/InternalServerError",
        },
      },
    },
  };

  // Existence check endpoint.
  swaggerSpec.paths[existsPath] = {
    parameters: [
      {
        $ref: "#/components/parameters/Id",
      },
    ],

    get: {
      tags: [resource.tag],
      summary: `Check whether ${resource.singular} exists by ID`,
      description:
        "Returns HTTP 200 for a valid ObjectId, whether or not the resource exists. The exists field indicates the result.",
      operationId: `exists${resource.operationSingular}ById`,
      responses: {
        200: jsonResponse(
          "Existence check completed",
          {
            $ref: "#/components/schemas/ResourceExists",
          },
          {
            id: "68ed1234567890abcdef1234",
            exists: true,
          },
        ),
        400: {
          $ref: "#/components/responses/BadRequest",
        },
        500: {
          $ref: "#/components/responses/InternalServerError",
        },
      },
    },
  };
}

